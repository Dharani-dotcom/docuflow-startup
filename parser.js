const fs = require('fs');
const path = require('path');

// 1. Target the folder containing the developer's source code
const srcDirectory = __dirname; 
const outputDir = path.join(__dirname, 'public');
if (!fs.existsSync(outputDir)) fs.mkdirSync(outputDir);

let accumulatedHtmlBlocks = '';

// Function to recursively scan folders for Javascript files
function scanDirectory(dir) {
    const files = fs.readdirSync(dir);

    files.forEach(file => {
        const fullPath = path.join(dir, file);
        
        // Skip node_modules and the public output folder
        if (file === 'node_modules' || file === 'public' || file === '.github') return;

        if (fs.statSync(fullPath).isDirectory()) {
            scanDirectory(fullPath); // Scan subfolders
        } else if (file.endsWith('.js')) {
            parseCodeComments(fullPath); // Parse the code file
        }
    });
}

// Extract tags out of the file blocks
function parseCodeComments(filePath) {
    const codeText = fs.readFileSync(filePath, 'utf8');
    const commentRegex = /\/\*\*([\s\(\S\)]*?)\*\//g;
    let match;

    while ((match = commentRegex.exec(codeText)) !== null) {
        const blockContent = match[1];
        const titleMatch = blockContent.match(/@title\s+(.*)/);
        const descMatch = blockContent.match(/@description\s+(.*)/);
        const paramMatch = blockContent.match(/@param\s+(.*)/);

        if (!titleMatch) continue; // Skip blocks without titles

        const title = titleMatch[1].trim();
        const description = descMatch ? descMatch[1].trim() : "No description provided.";
        const param = paramMatch ? paramMatch[1].trim() : "None";

        // Append this endpoint card to our site data
        accumulatedHtmlBlocks += `
        <div class="border border-white/5 bg-[#0a0a0a] rounded-xl p-6 shadow-2xl relative overflow-hidden mb-6">
            <span class="text-[10px] font-mono text-purple-400 uppercase tracking-widest bg-purple-500/10 px-2 py-0.5 rounded">API Endpoint</span>
            <h2 class="text-2xl font-bold tracking-tight text-white mt-2 mb-3">${title}</h2>
            
            <h3 class="text-xs font-semibold text-white/40 uppercase tracking-wider mt-4">Description</h3>
            <p class="text-white/80 mt-1 text-sm leading-relaxed">${description}</p>
            
            <h3 class="text-xs font-semibold text-white/40 uppercase tracking-wider mt-4">Parameters</h3>
            <div class="mt-2 p-3 bg-black/40 border border-white/5 rounded-lg font-mono text-xs">
                <span class="text-purple-300">${param.split(' - ')[0]}</span> 
                <span class="text-white/40">— ${param.split(' - ')[1] || ''}</span>
            </div>
        </div>`;
    }
}

console.log("🚀 DocuFlow Engine: Activating multi-file cloud deep scan...");
scanDirectory(srcDirectory);

// Build final clean master template webpage
const finalHtml = `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>DocuFlow Live Core Dashboard</title>
    <script src="https://tailwindcss.com"></script>
    <style>body { background-color: #030303; color: #ededed; }</style>
</head>
<body class="min-h-screen p-6 md:p-12 max-w-3xl mx-auto">
    <div class="flex items-center justify-between border-b border-white/5 pb-6 mb-8">
        <div>
            <h1 class="text-3xl font-bold tracking-tight text-white">System Documentation</h1>
            <p class="text-xs text-white/40 mt-1">Real-time continuous sync active</p>
        </div>
        <div class="text-right text-xs text-white/30">Generated by <span class="text-white/60 font-semibold">DocuFlow</span></div>
    </div>
    
    ${accumulatedHtmlBlocks || '<p class="text-white/40 text-sm">No documentation blocks detected in codebase.</p>'}
</body>
</html>`;

fs.writeFileSync(path.join(outputDir, 'index.html'), finalHtml);
console.log("✅ Master Suite Generated: public/index.html updated successfully!");
